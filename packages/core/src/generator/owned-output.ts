/**
 * The generator owns its output: writing a generated package records the
 * files it emitted, and removes the files an earlier run emitted that this run
 * no longer does.
 *
 * The ownership rule:
 *
 * - **The record.** Each generated package carries
 *   {@link OWNED_OUTPUT_RECORD_FILE} at its root, rewritten on every run. Its
 *   `files` list is the sorted, package-relative paths the run emitted,
 *   computed from the files the emitter handed to the writer, never from a
 *   glob over the directory. The record is deterministic and committed, so
 *   `pnpm generate:check` sees it drift like any other generated file.
 * - **Pruning.** After writing, every path in the previous owned-output set
 *   that this run did not emit is deleted, and a directory is removed only
 *   when that deletion left it empty. A file that is in no record is never
 *   touched: a package's `CHANGELOG.md`, handwritten tests, API reports and any
 *   other file the generator did not emit survive every run.
 * - **Bootstrap.** A package without a record has never been generated under
 *   this rule. Its previous set is then the files under it whose content opens
 *   with a generated header (see `./generated-header.ts`); a file without that
 *   header is kept. After that first run the record takes over.
 *
 * Regenerating after a manifest drops an operation or a resource therefore
 * leaves the package tree as a fresh generate into an empty directory would,
 * apart from the files the generator never owned.
 *
 * @packageDocumentation
 */

import { mkdir, readFile, readdir, rmdir, unlink, writeFile } from 'node:fs/promises'
import { isAbsolute, join, posix, sep } from 'node:path'
import { hasGeneratedHeader } from './generated-header.js'
import { writeFiles } from './write.js'

/**
 * The name of the owned-output record at the root of each generated package.
 */
export const OWNED_OUTPUT_RECORD_FILE = '.macts-generated.json'

/** The record's one-line explanation of itself, written as its `$comment`. */
const RECORD_COMMENT =
  'Generated by macts generate; do not edit. The files the generator emitted into this package: the next generation deletes any listed file it no longer emits.'

/**
 * Directories the bootstrap never looks inside: build output and installed
 * dependencies (which the generated `.gitignore` excludes), and dot-directories
 * such as tool caches. Files there are never generator output.
 */
const BOOTSTRAP_SKIPPED_DIRECTORIES = new Set(['dist', 'node_modules'])

/**
 * Where a package's previous owned-output set came from: its record, or, for a
 * package without one, the files carrying a generated header.
 */
export type OwnedOutputSource = 'record' | 'headers'

/**
 * The outcome of writing one generated package.
 *
 * Every path is package-relative, uses `/` separators, and every list is
 * sorted.
 */
export interface GeneratedPackageWriteResult {
  /** The paths this run emitted: the package's new owned-output set, as recorded. */
  readonly emitted: readonly string[]
  /** Where the previous owned-output set came from. */
  readonly previousSource: OwnedOutputSource
  /** The previous owned-output set. */
  readonly previous: readonly string[]
  /** The previously owned paths this run did not emit, which were deleted. */
  readonly pruned: readonly string[]
}

/** An error code from a failed filesystem call, if it carries one. */
function errorCode(error: unknown): string | undefined {
  if (error instanceof Error && 'code' in error && typeof error.code === 'string') {
    return error.code
  }
  return undefined
}

/**
 * The canonical package-relative form of a generated file's path: `/`
 * separators, normalized, and confined to the package.
 *
 * @throws When the path is empty, absolute, leaves the package, or names the
 * record itself.
 */
export function toPackagePath(path: string): string {
  const slashed = path.split(sep).join('/')
  if (slashed.length === 0 || isAbsolute(path) || posix.isAbsolute(slashed)) {
    throw new Error(`Generated file path must be package-relative, got "${path}".`)
  }
  const normalized = posix.normalize(slashed)
  if (normalized === '.' || normalized === '..' || normalized.startsWith('../')) {
    throw new Error(`Generated file path must stay inside the package, got "${path}".`)
  }
  if (normalized === OWNED_OUTPUT_RECORD_FILE) {
    throw new Error(`The generator may not emit its own record, ${OWNED_OUTPUT_RECORD_FILE}.`)
  }
  return normalized
}

/** Whether a path is already in the canonical form {@link toPackagePath} gives. */
function isCanonicalPackagePath(path: string): boolean {
  try {
    return toPackagePath(path) === path
  } catch {
    return false
  }
}

/** The sorted, de-duplicated owned-output set of the files one run emits. */
export function ownedOutputPaths(files: readonly { readonly path: string }[]): string[] {
  return [...new Set(files.map((file) => toPackagePath(file.path)))].sort()
}

/** The record's content for an owned-output set. */
export function renderOwnedOutputRecord(paths: readonly string[]): string {
  const record = { $comment: RECORD_COMMENT, files: [...new Set(paths)].sort() }
  return `${JSON.stringify(record, null, 2)}\n`
}

/**
 * The owned-output set a record holds.
 *
 * @param content - The record file's content
 * @param location - The record's path, named in errors
 * @throws When the content is not a record, or a listed path is not a
 * canonical package-relative path. A malformed record is never guessed at,
 * because its paths are about to be deleted.
 */
export function parseOwnedOutputRecord(content: string, location: string): string[] {
  let parsed: unknown
  try {
    parsed = JSON.parse(content)
  } catch (error) {
    throw new Error(`${location} is not valid JSON: ${String(error)}`)
  }
  if (typeof parsed !== 'object' || parsed === null || !('files' in parsed)) {
    throw new Error(`${location} is not an owned-output record: it has no "files" list.`)
  }
  const { files } = parsed
  if (!Array.isArray(files)) {
    throw new Error(`${location} is not an owned-output record: "files" is not a list.`)
  }
  return files.map((entry: unknown) => {
    if (typeof entry === 'string' && isCanonicalPackagePath(entry)) return entry
    throw new Error(
      `${location} lists ${JSON.stringify(entry)}, which is not a canonical package-relative path.`
    )
  })
}

/** The paths of the previous set that the current run did not emit, sorted. */
export function stalePaths(previous: readonly string[], emitted: readonly string[]): string[] {
  const current = new Set(emitted)
  return [...new Set(previous)].filter((path) => !current.has(path)).sort()
}

/**
 * The package-relative paths of every file under a package whose content
 * opens with a generated header, sorted. Symbolic links and
 * {@link BOOTSTRAP_SKIPPED_DIRECTORIES} are not followed.
 */
export async function findHeaderBearingFiles(packageDir: string): Promise<string[]> {
  const found: string[] = []
  async function visit(relativeDir: string): Promise<void> {
    let entries
    try {
      entries = await readdir(join(packageDir, relativeDir), { withFileTypes: true })
    } catch (error) {
      if (errorCode(error) === 'ENOENT') return
      throw error
    }
    for (const entry of entries) {
      const relativePath = relativeDir === '' ? entry.name : `${relativeDir}/${entry.name}`
      if (entry.isDirectory()) {
        if (entry.name.startsWith('.') || BOOTSTRAP_SKIPPED_DIRECTORIES.has(entry.name)) continue
        await visit(relativePath)
      } else if (entry.isFile()) {
        const content = await readFile(join(packageDir, relativePath), 'utf-8')
        if (hasGeneratedHeader(content)) found.push(relativePath)
      }
    }
  }
  await visit('')
  return found.sort()
}

/** The previous owned-output set of a package: its record, or the bootstrap set. */
export async function readPreviousOwnedOutput(
  packageDir: string
): Promise<{ readonly source: OwnedOutputSource; readonly files: readonly string[] }> {
  const recordPath = join(packageDir, OWNED_OUTPUT_RECORD_FILE)
  let content: string
  try {
    content = await readFile(recordPath, 'utf-8')
  } catch (error) {
    if (errorCode(error) !== 'ENOENT') throw error
    return { source: 'headers', files: await findHeaderBearingFiles(packageDir) }
  }
  return { source: 'record', files: parseOwnedOutputRecord(content, recordPath) }
}

/**
 * Delete owned files from a package, then remove each directory the deletions
 * left empty, up to (never including) the package directory.
 *
 * @returns The paths actually deleted; a path already absent is skipped.
 */
export async function pruneOwnedOutput(
  packageDir: string,
  paths: readonly string[]
): Promise<string[]> {
  const deleted: string[] = []
  for (const path of paths) {
    try {
      await unlink(join(packageDir, toPackagePath(path)))
    } catch (error) {
      if (errorCode(error) === 'ENOENT') continue
      throw error
    }
    deleted.push(path)
    let parent = posix.dirname(path)
    while (parent !== '.') {
      try {
        await rmdir(join(packageDir, parent))
      } catch (error) {
        const code = errorCode(error)
        if (code === 'ENOTEMPTY' || code === 'EEXIST' || code === 'ENOENT') break
        throw error
      }
      parent = posix.dirname(parent)
    }
  }
  return deleted
}

/**
 * Write one generated package: its files, then the pruning of what the
 * previous run emitted and this one did not, then its owned-output record.
 *
 * The record is written last, so a run interrupted before it finishes leaves
 * the previous record in place and the next run prunes again.
 *
 * @param files - Every file the emitter produced for the package, with
 * package-relative paths
 * @param packageDir - The package's directory
 * @returns What was emitted, where the previous set came from, and what was
 * pruned
 */
export async function writeGeneratedPackage(
  files: { path: string; content: string }[],
  packageDir: string
): Promise<GeneratedPackageWriteResult> {
  const emitted = ownedOutputPaths(files)
  const previous = await readPreviousOwnedOutput(packageDir)
  await writeFiles(files, packageDir)
  const pruned = await pruneOwnedOutput(packageDir, stalePaths(previous.files, emitted))
  await mkdir(packageDir, { recursive: true })
  await writeFile(
    join(packageDir, OWNED_OUTPUT_RECORD_FILE),
    renderOwnedOutputRecord(emitted),
    'utf-8'
  )
  return { emitted, previousSource: previous.source, previous: previous.files, pruned }
}
