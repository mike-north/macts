/**
 * Tests for the `.gitattributes` the generator emits into each generated app
 * package.
 *
 * Expected values follow the marking rule in `./git-attributes.ts`: the
 * package's `src/` tree and every other file the generator owns at the package
 * root are marked `linguist-generated=true`, except `package.json`, whose
 * version and dependency ranges changesets rewrites and whose changes reviewers
 * read as hand-written. Root files are anchored with a leading `/`, so a file of
 * the same name deeper in the package is not swept in.
 *
 * The `git check-attr` cases run real git in a scratch repository, so they
 * check what GitHub and other `linguist-generated` readers see.
 *
 * @see https://git-scm.com/docs/gitattributes
 * @see https://github.com/github-linguist/linguist/blob/main/docs/overrides.md#generated-code
 */

import { spawnSync } from 'node:child_process'
import { mkdtemp, readFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { afterEach, beforeAll, beforeEach, describe, expect, it } from 'vitest'
import type { AppManifest } from '../manifest/index.js'
import { loadManifest } from '../manifest/loader.js'
import { GIT_ATTRIBUTES_FILE, generateGitAttributes } from './git-attributes.js'
import { generateConsolidatedPackages } from './orchestrate.js'
import {
  OWNED_OUTPUT_RECORD_FILE,
  parseOwnedOutputRecord,
  writeGeneratedPackage,
} from './owned-output.js'

const MANIFESTS_DIR = resolve(process.cwd(), '../../manifests')

/** The attribute every marking line sets. */
const GENERATED = 'linguist-generated=true'

/** Emitter output with the given paths and placeholder content. */
function emit(paths: readonly string[]): { path: string; content: string }[] {
  return paths.map((path) => ({ path, content: 'export {}\n' }))
}

/** The non-comment, non-blank lines of a `.gitattributes`. */
function rules(content: string): string[] {
  return content.split('\n').filter((line) => line.length > 0 && !line.startsWith('#'))
}

/** The content of one emitted file. */
function contentOf(files: readonly { path: string; content: string }[], path: string): string {
  const file = files.find((candidate) => candidate.path === path)
  if (file === undefined) throw new Error(`${path} was not emitted`)
  return file.content
}

describe('generateGitAttributes', () => {
  it('emits .gitattributes at the package root', () => {
    expect(generateGitAttributes(emit(['src/index.ts'])).path).toBe('.gitattributes')
    expect(GIT_ATTRIBUTES_FILE).toBe('.gitattributes')
  })

  it('marks src/**, itself, the record, and every other owned file except package.json', () => {
    const { content } = generateGitAttributes(
      emit([
        'src/index.ts',
        'src/cli/commands/widgets/list.ts',
        'package.json',
        'tsconfig.json',
        'tsup.config.ts',
        '.gitignore',
        'LICENSE',
        'api-extractor.json',
        'api-report/.gitkeep',
      ])
    )
    expect(rules(content)).toEqual([
      `src/** ${GENERATED}`,
      `/.gitattributes ${GENERATED}`,
      `/.gitignore ${GENERATED}`,
      `/.macts-generated.json ${GENERATED}`,
      `/LICENSE ${GENERATED}`,
      `/api-extractor.json ${GENERATED}`,
      `/api-report/.gitkeep ${GENERATED}`,
      `/tsconfig.json ${GENERATED}`,
      `/tsup.config.ts ${GENERATED}`,
    ])
  })

  it('never marks package.json', () => {
    const { content } = generateGitAttributes(emit(['package.json', 'src/index.ts']))
    expect(rules(content).filter((rule) => rule.includes('package.json'))).toEqual([])
  })

  it('opens with a do-not-edit comment', () => {
    const { content } = generateGitAttributes(emit(['src/index.ts']))
    expect(content.split('\n')[0]).toBe('# Generated by macts generate; do not edit.')
    expect(content.endsWith('\n')).toBe(true)
  })

  it('omits src/** when the package emits nothing under src/', () => {
    expect(rules(generateGitAttributes(emit(['LICENSE'])).content)).toEqual([
      `/.gitattributes ${GENERATED}`,
      `/.macts-generated.json ${GENERATED}`,
      `/LICENSE ${GENERATED}`,
    ])
  })

  it('does not depend on the order or repetition of the emitted files', () => {
    const forward = generateGitAttributes(emit(['LICENSE', 'src/a.ts', 'tsconfig.json']))
    const backward = generateGitAttributes(
      emit(['tsconfig.json', 'src/a.ts', 'LICENSE', 'tsconfig.json'])
    )
    expect(backward).toEqual(forward)
  })

  it('rejects a path it cannot write as a literal gitattributes pattern', () => {
    for (const path of ['my file.json', 'config*.json', 'a?.json', '[x].json', 'a\\b.json']) {
      expect(() => generateGitAttributes(emit([path]))).toThrow(path)
    }
  })

  it('rejects a path that leaves the package', () => {
    expect(() => generateGitAttributes(emit(['../outside.json']))).toThrow()
  })
})

describe('the real generator', () => {
  let manifest: AppManifest
  beforeAll(async () => {
    manifest = await loadManifest(join(MANIFESTS_DIR, 'google-chrome', 'app.yaml'))
  })

  it('emits .gitattributes into the client package, marking its sources', () => {
    const { client } = generateConsolidatedPackages(manifest, { appName: 'google-chrome' })
    expect(rules(contentOf(client.files, '.gitattributes'))).toEqual([
      `src/** ${GENERATED}`,
      `/.gitattributes ${GENERATED}`,
      `/.gitignore ${GENERATED}`,
      `/.macts-generated.json ${GENERATED}`,
      `/LICENSE ${GENERATED}`,
      `/api-extractor.contract.json ${GENERATED}`,
      `/api-extractor.json ${GENERATED}`,
      `/api-report/.gitkeep ${GENERATED}`,
      `/tsconfig.json ${GENERATED}`,
      `/tsup.config.ts ${GENERATED}`,
    ])
  })

  it('emits .gitattributes into the server package, marking its sources', () => {
    const { server } = generateConsolidatedPackages(manifest, { appName: 'google-chrome' })
    expect(rules(contentOf(server.files, '.gitattributes'))).toEqual([
      `src/** ${GENERATED}`,
      `/.gitattributes ${GENERATED}`,
      `/.gitignore ${GENERATED}`,
      `/.macts-generated.json ${GENERATED}`,
      `/LICENSE ${GENERATED}`,
      `/tsconfig.json ${GENERATED}`,
      `/tsup.config.ts ${GENERATED}`,
    ])
  })

  it('emits exactly one .gitattributes per package', () => {
    const { client, server } = generateConsolidatedPackages(manifest, { appName: 'google-chrome' })
    for (const pkg of [client, server]) {
      expect(pkg.files.filter((file) => file.path === '.gitattributes')).toHaveLength(1)
    }
  })

  it('marks every root file it emits, apart from package.json', () => {
    const { client, server } = generateConsolidatedPackages(manifest, { appName: 'google-chrome' })
    for (const pkg of [client, server]) {
      const marked = new Set(rules(contentOf(pkg.files, '.gitattributes')))
      for (const { path } of pkg.files) {
        if (path.startsWith('src/') || path === 'package.json') continue
        expect(marked).toContain(`/${path} ${GENERATED}`)
      }
    }
  })
})

describe('writing a generated package', () => {
  let root: string

  beforeEach(async () => {
    root = await mkdtemp(join(tmpdir(), 'macts-git-attributes-'))
  })

  afterEach(async () => {
    await rm(root, { recursive: true, force: true })
  })

  /** A git environment isolated from the developer's own configuration. */
  const GIT_ENV = {
    ...process.env,
    GIT_CONFIG_GLOBAL: '/dev/null',
    GIT_CONFIG_NOSYSTEM: '1',
  }

  /** The `linguist-generated` value git reports for a path in the scratch repository. */
  function linguistGenerated(path: string): string {
    const run = spawnSync('git', ['check-attr', 'linguist-generated', '--', path], {
      cwd: root,
      env: GIT_ENV,
      encoding: 'utf-8',
    })
    if (run.status !== 0) throw new Error(`git check-attr failed: ${run.stderr}`)
    // Output is `<path>: linguist-generated: <value>`.
    return run.stdout.trim().split(': ').at(-1) ?? ''
  }

  it('records .gitattributes in .macts-generated.json, as owned output', async () => {
    const manifest = await loadManifest(join(MANIFESTS_DIR, 'google-chrome', 'app.yaml'))
    const { client, server } = generateConsolidatedPackages(manifest, { appName: 'google-chrome' })
    for (const pkg of [client, server]) {
      const packageDir = join(root, pkg.dir)
      await writeGeneratedPackage(pkg.files, packageDir)
      const recordPath = join(packageDir, OWNED_OUTPUT_RECORD_FILE)
      const recorded = parseOwnedOutputRecord(await readFile(recordPath, 'utf-8'), recordPath)
      expect(recorded).toContain('.gitattributes')
      expect(await readFile(join(packageDir, '.gitattributes'), 'utf-8')).toBe(
        contentOf(pkg.files, '.gitattributes')
      )
    }
  })

  it('makes git report the generated files, and only those, as linguist-generated', async () => {
    const init = spawnSync('git', ['init', '--quiet'], { cwd: root, env: GIT_ENV })
    expect(init.status).toBe(0)
    const files = emit([
      'src/index.ts',
      'src/contract/index.ts',
      'package.json',
      'tsconfig.json',
      'LICENSE',
    ])
    await writeGeneratedPackage(
      [...files, generateGitAttributes(files)],
      join(root, 'packages/widgets')
    )

    expect(linguistGenerated('packages/widgets/src/index.ts')).toBe('true')
    expect(linguistGenerated('packages/widgets/src/contract/index.ts')).toBe('true')
    expect(linguistGenerated('packages/widgets/tsconfig.json')).toBe('true')
    expect(linguistGenerated('packages/widgets/LICENSE')).toBe('true')
    expect(linguistGenerated('packages/widgets/.gitattributes')).toBe('true')
    expect(linguistGenerated('packages/widgets/.macts-generated.json')).toBe('true')
    // Not generator-owned, or deliberately left unmarked.
    expect(linguistGenerated('packages/widgets/package.json')).toBe('unspecified')
    expect(linguistGenerated('packages/widgets/CHANGELOG.md')).toBe('unspecified')
    // A root rule is anchored: a same-named file deeper down is not swept in.
    expect(linguistGenerated('packages/widgets/test/tsconfig.json')).toBe('unspecified')
    // Nothing outside the package is affected.
    expect(linguistGenerated('packages/handwritten/src/index.ts')).toBe('unspecified')
    expect(linguistGenerated('src/index.ts')).toBe('unspecified')
  })
})
