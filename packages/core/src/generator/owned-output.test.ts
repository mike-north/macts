/**
 * Tests for the generator's owned-output record and pruning.
 *
 * The pure helpers are tested directly. `writeGeneratedPackage` is tested over
 * a temporary package directory with hand-written emitter output, so each case
 * controls exactly what the previous run left behind.
 *
 * Expected values follow the ownership rule in `./owned-output.ts`: the record
 * lists the sorted package-relative paths a run emitted; pruning deletes the
 * previously owned paths the run did not emit, and nothing else; a package
 * without a record takes its header-bearing files as the previous set.
 *
 * @see https://github.com/mike-north/macts/issues/179
 */

import { mkdir, mkdtemp, readFile, readdir, rm, symlink, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import {
  OWNED_OUTPUT_RECORD_FILE,
  findHeaderBearingFiles,
  ownedOutputPaths,
  parseOwnedOutputRecord,
  pruneOwnedOutput,
  renderOwnedOutputRecord,
  stalePaths,
  toPackagePath,
  writeGeneratedPackage,
} from './owned-output.js'

/** Content that opens with the SDK emitter's generated header. */
const HEADED = `/**
 * Widget client for Example SDK.
 * Auto-generated - do not edit.
 */
export {}
`

/** Content of a generated file the emitters write without a header. */
const UNHEADED = `import { Command } from 'clipanion'
export {}
`

/** A package's `package.json`, which makes its directory a package. */
const PACKAGE_JSON = '{ "name": "@macts/example" }\n'

let packageDir: string

beforeEach(async () => {
  packageDir = await mkdtemp(join(tmpdir(), 'macts-owned-output-'))
})

afterEach(async () => {
  await rm(packageDir, { recursive: true, force: true })
})

/** Write files into the package directory, creating parents. */
async function plant(files: Record<string, string>): Promise<void> {
  for (const [path, content] of Object.entries(files)) {
    await mkdir(dirname(join(packageDir, path)), { recursive: true })
    await writeFile(join(packageDir, path), content, 'utf-8')
  }
}

/** Write a record that lists the given paths as the previous run's output. */
async function plantRecord(paths: string[]): Promise<void> {
  await plant({ [OWNED_OUTPUT_RECORD_FILE]: renderOwnedOutputRecord(paths) })
}

/** Every file under the package directory, package-relative, sorted. */
async function tree(): Promise<string[]> {
  const entries = await readdir(packageDir, { recursive: true, withFileTypes: true })
  return entries
    .filter((entry) => entry.isFile())
    .map((entry) => join(entry.parentPath, entry.name).slice(packageDir.length + 1))
    .sort()
}

/** Whether a package-relative directory exists. */
async function directoryExists(path: string): Promise<boolean> {
  try {
    await readdir(join(packageDir, path))
    return true
  } catch {
    return false
  }
}

/** The files a run emits, as the emitter hands them to the writer. */
function emit(paths: string[]): { path: string; content: string }[] {
  return paths.map((path) => ({ path, content: `// ${path}\n` }))
}

describe('toPackagePath', () => {
  it('normalizes a package-relative path', () => {
    expect(toPackagePath('src/./cli/../index.ts')).toBe('src/index.ts')
  })

  it('rejects an absolute path', () => {
    expect(() => toPackagePath('/etc/passwd')).toThrow('package-relative')
  })

  it('rejects a path that leaves the package', () => {
    expect(() => toPackagePath('../other/src/index.ts')).toThrow('inside the package')
    expect(() => toPackagePath('src/../../x.ts')).toThrow('inside the package')
  })

  it('rejects the empty path and the package directory itself', () => {
    expect(() => toPackagePath('')).toThrow()
    expect(() => toPackagePath('.')).toThrow('inside the package')
  })

  it('rejects the record itself', () => {
    expect(() => toPackagePath(OWNED_OUTPUT_RECORD_FILE)).toThrow('its own record')
  })
})

describe('ownedOutputPaths', () => {
  it('is the sorted, de-duplicated set of emitted paths', () => {
    expect(ownedOutputPaths(emit(['src/b.ts', 'package.json', 'src/a.ts', 'src/b.ts']))).toEqual([
      'package.json',
      'src/a.ts',
      'src/b.ts',
    ])
  })

  it('sorts by code unit, independent of locale', () => {
    expect(ownedOutputPaths(emit(['src/b.ts', 'src/B.ts', 'src/a.ts']))).toEqual([
      'src/B.ts',
      'src/a.ts',
      'src/b.ts',
    ])
  })

  it('is empty when nothing is emitted', () => {
    expect(ownedOutputPaths([])).toEqual([])
  })
})

describe('renderOwnedOutputRecord', () => {
  it('holds a one-line comment and the sorted files', () => {
    const record = JSON.parse(renderOwnedOutputRecord(['src/b.ts', 'src/a.ts'])) as {
      $comment: unknown
      files: unknown
    }
    expect(Object.keys(record)).toEqual(['$comment', 'files'])
    expect(record.$comment).toMatch(/^Generated by macts generate; do not edit\.[^\n]*$/)
    expect(record.files).toEqual(['src/a.ts', 'src/b.ts'])
  })

  it('is deterministic: the same set renders the same bytes in any order', () => {
    expect(renderOwnedOutputRecord(['b', 'a', 'c'])).toBe(renderOwnedOutputRecord(['c', 'b', 'a']))
  })

  it('ends with a newline', () => {
    expect(renderOwnedOutputRecord([]).endsWith('}\n')).toBe(true)
  })

  it('round-trips through parseOwnedOutputRecord', () => {
    const paths = ['package.json', 'src/index.ts']
    expect(parseOwnedOutputRecord(renderOwnedOutputRecord(paths), 'record')).toEqual(paths)
  })
})

describe('parseOwnedOutputRecord', () => {
  it('rejects content that is not JSON', () => {
    expect(() => parseOwnedOutputRecord('{', 'pkg/.macts-generated.json')).toThrow(
      'pkg/.macts-generated.json is not valid JSON'
    )
  })

  it('rejects a record without a files list', () => {
    expect(() => parseOwnedOutputRecord('{}', 'record')).toThrow('no "files" list')
    expect(() => parseOwnedOutputRecord('null', 'record')).toThrow('no "files" list')
    expect(() => parseOwnedOutputRecord('{"files": "src/a.ts"}', 'record')).toThrow(
      '"files" is not a list'
    )
  })

  it('rejects a listed path that is not a string', () => {
    expect(() => parseOwnedOutputRecord('{"files": [1]}', 'record')).toThrow(
      'record lists 1, which is not a canonical package-relative path'
    )
  })

  it('rejects a listed path that leaves the package, so pruning can never reach outside it', () => {
    expect(() => parseOwnedOutputRecord('{"files": ["../core/src/index.ts"]}', 'record')).toThrow(
      'not a canonical package-relative path'
    )
    expect(() => parseOwnedOutputRecord('{"files": ["/tmp/x"]}', 'record')).toThrow(
      'not a canonical package-relative path'
    )
  })

  it('rejects a listed path that is not in canonical form', () => {
    expect(() => parseOwnedOutputRecord('{"files": ["src/./a.ts"]}', 'record')).toThrow(
      'not a canonical package-relative path'
    )
  })
})

describe('stalePaths', () => {
  it('is the previous paths the run did not emit, sorted', () => {
    expect(stalePaths(['src/c.ts', 'src/a.ts', 'src/b.ts'], ['src/a.ts'])).toEqual([
      'src/b.ts',
      'src/c.ts',
    ])
  })

  it('is empty when the run emitted everything it did before', () => {
    expect(stalePaths(['src/a.ts'], ['src/a.ts', 'src/new.ts'])).toEqual([])
  })

  it('is empty without a previous set', () => {
    expect(stalePaths([], ['src/a.ts'])).toEqual([])
  })
})

describe('findHeaderBearingFiles', () => {
  it('finds the files that open with a generated header, sorted', async () => {
    await plant({
      'src/resources/widget.ts': HEADED,
      'src/types.ts': HEADED,
      'src/cli/commands/widgets/list.ts': UNHEADED,
      'CHANGELOG.md': '# @macts/example\n',
    })
    expect(await findHeaderBearingFiles(packageDir)).toEqual([
      'src/resources/widget.ts',
      'src/types.ts',
    ])
  })

  it('does not look inside build output, dependencies or dot-directories', async () => {
    await plant({
      'dist/index.js': HEADED,
      'node_modules/dep/index.ts': HEADED,
      '.turbo/cache.ts': HEADED,
      'src/index.ts': HEADED,
    })
    expect(await findHeaderBearingFiles(packageDir)).toEqual(['src/index.ts'])
  })

  it('is empty for a package directory that does not exist yet', async () => {
    expect(await findHeaderBearingFiles(join(packageDir, 'missing'))).toEqual([])
  })

  it('does not look inside a subdirectory that is a package of its own', async () => {
    await plant({
      'src/index.ts': HEADED,
      'other/package.json': PACKAGE_JSON,
      'other/src/x.ts': HEADED,
    })
    expect(await findHeaderBearingFiles(packageDir)).toEqual(['src/index.ts'])
  })

  it('keeps a file whose header lies beyond the prefix it reads', async () => {
    const longComment = ` * ${'x'.repeat(100)}\n`.repeat(50)
    await plant({ 'src/long.ts': `/**\n${longComment} * Auto-generated - do not edit.\n */\n` })
    expect(await findHeaderBearingFiles(packageDir)).toEqual([])
  })
})

describe('pruneOwnedOutput', () => {
  it('removes a directory the deletions left empty, and its emptied parents', async () => {
    await plant({ 'src/cli/commands/connections/list.ts': UNHEADED, 'src/index.ts': UNHEADED })
    expect(await pruneOwnedOutput(packageDir, ['src/cli/commands/connections/list.ts'])).toEqual([
      'src/cli/commands/connections/list.ts',
    ])
    expect(await directoryExists('src/cli')).toBe(false)
    expect(await tree()).toEqual(['src/index.ts'])
  })

  it('keeps a directory that still holds another file', async () => {
    await plant({
      'src/cli/commands/connections/list.ts': UNHEADED,
      'src/cli/commands/connections/notes.md': 'kept\n',
    })
    await pruneOwnedOutput(packageDir, ['src/cli/commands/connections/list.ts'])
    expect(await tree()).toEqual(['src/cli/commands/connections/notes.md'])
  })

  it('leaves alone an empty directory the deletions did not empty', async () => {
    await plant({ 'src/a.ts': UNHEADED })
    await mkdir(join(packageDir, 'api-report'))
    await pruneOwnedOutput(packageDir, ['src/a.ts'])
    expect(await directoryExists('api-report')).toBe(true)
  })

  it('skips a previously owned path that is already gone', async () => {
    expect(await pruneOwnedOutput(packageDir, ['src/gone.ts'])).toEqual([])
  })

  it('refuses to delete through a symbolically linked directory, and deletes nothing there', async () => {
    const outside = await mkdtemp(join(tmpdir(), 'macts-owned-output-outside-'))
    try {
      await writeFile(join(outside, 'x.ts'), HEADED, 'utf-8')
      await mkdir(join(packageDir, 'src'), { recursive: true })
      await symlink(outside, join(packageDir, 'src/link'))

      await expect(pruneOwnedOutput(packageDir, ['src/link/x.ts'])).rejects.toThrow(
        'is a symbolic link'
      )
      expect(await readFile(join(outside, 'x.ts'), 'utf-8')).toBe(HEADED)
    } finally {
      await rm(outside, { recursive: true, force: true })
    }
  })

  it('never deletes the package directory itself', async () => {
    await plant({ 'README.md': 'x\n' })
    await pruneOwnedOutput(packageDir, ['README.md'])
    expect(await directoryExists('.')).toBe(true)
  })
})

describe('writeGeneratedPackage', () => {
  it('writes the emitted files and a record of exactly them', async () => {
    const result = await writeGeneratedPackage(
      emit(['src/index.ts', 'package.json']),
      join(packageDir, 'fresh')
    )
    expect(result.emitted).toEqual(['package.json', 'src/index.ts'])
    const record = await readFile(join(packageDir, 'fresh', OWNED_OUTPUT_RECORD_FILE), 'utf-8')
    expect(parseOwnedOutputRecord(record, 'record')).toEqual(['package.json', 'src/index.ts'])
  })

  it('does not list the record in itself', async () => {
    await writeGeneratedPackage(emit(['src/index.ts']), packageDir)
    const record = await readFile(join(packageDir, OWNED_OUTPUT_RECORD_FILE), 'utf-8')
    expect(parseOwnedOutputRecord(record, 'record')).not.toContain(OWNED_OUTPUT_RECORD_FILE)
  })

  it('rewrites the same record when the run emits the same files', async () => {
    await writeGeneratedPackage(emit(['src/b.ts', 'src/a.ts']), packageDir)
    const first = await readFile(join(packageDir, OWNED_OUTPUT_RECORD_FILE), 'utf-8')
    await writeGeneratedPackage(emit(['src/a.ts', 'src/b.ts']), packageDir)
    expect(await readFile(join(packageDir, OWNED_OUTPUT_RECORD_FILE), 'utf-8')).toBe(first)
  })

  describe('with a record', () => {
    it('prunes the recorded paths the run no longer emits', async () => {
      await plant({
        'src/index.ts': UNHEADED,
        'src/resources/connection.ts': HEADED,
        'src/cli/commands/connections/list.ts': UNHEADED,
      })
      await plantRecord([
        'src/cli/commands/connections/list.ts',
        'src/index.ts',
        'src/resources/connection.ts',
      ])

      const result = await writeGeneratedPackage(emit(['src/index.ts']), packageDir)

      expect(result.previousSource).toBe('record')
      expect(result.pruned).toEqual([
        'src/cli/commands/connections/list.ts',
        'src/resources/connection.ts',
      ])
      expect(await tree()).toEqual([OWNED_OUTPUT_RECORD_FILE, 'src/index.ts'])
    })

    it('keeps a header-bearing file the record does not list', async () => {
      await plant({ 'src/handwritten.ts': HEADED })
      await plantRecord(['src/index.ts'])

      const result = await writeGeneratedPackage(emit(['src/index.ts']), packageDir)

      expect(result.pruned).toEqual([])
      expect(await tree()).toContain('src/handwritten.ts')
    })

    it('rejects a malformed record and deletes nothing', async () => {
      await plant({ 'src/stale.ts': UNHEADED, [OWNED_OUTPUT_RECORD_FILE]: '{"files": ["../x"]}' })

      await expect(writeGeneratedPackage(emit(['src/index.ts']), packageDir)).rejects.toThrow(
        'not a canonical package-relative path'
      )
      expect(await tree()).toEqual([OWNED_OUTPUT_RECORD_FILE, 'src/stale.ts'])
    })
  })

  describe('without a record (bootstrap)', () => {
    it('takes the header-bearing files as the previous set, and prunes a stale one', async () => {
      await plant({
        'package.json': PACKAGE_JSON,
        'src/types.ts': HEADED,
        'src/resources/connection.ts': HEADED,
      })

      const result = await writeGeneratedPackage(emit(['src/types.ts']), packageDir)

      expect(result.previousSource).toBe('headers')
      expect(result.previous).toEqual(['src/resources/connection.ts', 'src/types.ts'])
      expect(result.pruned).toEqual(['src/resources/connection.ts'])
      expect(await tree()).toEqual([OWNED_OUTPUT_RECORD_FILE, 'package.json', 'src/types.ts'])
    })

    it('keeps a stale file without a header', async () => {
      await plant({
        'package.json': PACKAGE_JSON,
        'src/cli/commands/connections/list.ts': UNHEADED,
      })

      const result = await writeGeneratedPackage(emit(['src/index.ts']), packageDir)

      expect(result.previousSource).toBe('headers')
      expect(result.pruned).toEqual([])
      expect(await tree()).toContain('src/cli/commands/connections/list.ts')
    })

    it('keeps the files of a package nested inside the package directory', async () => {
      // A mistaken output directory that holds other packages, such as
      // `--out-dir packages` for a single app, must not prune those packages.
      await plant({
        'package.json': PACKAGE_JSON,
        'other/package.json': PACKAGE_JSON,
        'other/src/x.ts': HEADED,
      })

      const result = await writeGeneratedPackage(emit(['src/index.ts']), packageDir)

      expect(result.previous).toEqual([])
      expect(result.pruned).toEqual([])
      expect(await tree()).toContain('other/src/x.ts')
    })

    it('has no previous set in a directory that is not a package, and prunes nothing', async () => {
      await plant({ 'calendar/src/types.ts': HEADED, 'src/stale.ts': HEADED })

      const result = await writeGeneratedPackage(emit(['src/index.ts']), packageDir)

      expect(result.previousSource).toBe('none')
      expect(result.previous).toEqual([])
      expect(result.pruned).toEqual([])
      expect(await tree()).toEqual(
        expect.arrayContaining(['calendar/src/types.ts', 'src/stale.ts'])
      )
    })

    it('hands over to the record on the next run', async () => {
      await plant({
        'package.json': PACKAGE_JSON,
        'src/cli/commands/connections/list.ts': UNHEADED,
      })
      await writeGeneratedPackage(
        emit(['src/index.ts', 'src/cli/commands/connections/list.ts']),
        packageDir
      )

      const result = await writeGeneratedPackage(emit(['src/index.ts']), packageDir)

      expect(result.previousSource).toBe('record')
      expect(result.pruned).toEqual(['src/cli/commands/connections/list.ts'])
    })
  })

  describe('an interrupted run', () => {
    it('leaves a record of the previous set and every file the run meant to write', async () => {
      // A file where the run needs a directory makes writing fail part way.
      await plant({ 'src/old.ts': UNHEADED, lib: 'not a directory\n' })
      await plantRecord(['src/old.ts'])

      await expect(
        writeGeneratedPackage(emit(['src/new.ts', 'lib/index.ts']), packageDir)
      ).rejects.toThrow()

      const record = await readFile(join(packageDir, OWNED_OUTPUT_RECORD_FILE), 'utf-8')
      expect(parseOwnedOutputRecord(record, 'record')).toEqual([
        'lib/index.ts',
        'src/new.ts',
        'src/old.ts',
      ])
    })
  })

  describe('files the generator does not own', () => {
    it('keeps CHANGELOG.md, LICENSE, a handwritten test and API reports', async () => {
      await plant({
        'CHANGELOG.md': '# @macts/example\n',
        LICENSE: 'MIT License\n',
        'src/widget.test.ts': `import { it } from 'vitest'\n`,
        'api-report/example.api.md': '## API Report File\n',
        'src/stale.ts': UNHEADED,
      })
      await plantRecord(['LICENSE', 'src/index.ts', 'src/stale.ts'])

      const result = await writeGeneratedPackage(emit(['LICENSE', 'src/index.ts']), packageDir)

      expect(result.pruned).toEqual(['src/stale.ts'])
      expect(await tree()).toEqual([
        OWNED_OUTPUT_RECORD_FILE,
        'CHANGELOG.md',
        'LICENSE',
        'api-report/example.api.md',
        'src/index.ts',
        'src/widget.test.ts',
      ])
    })
  })
})
