/**
 * The `.gitattributes` the generator emits at the root of each generated app
 * package, marking the files the generator owns there as `linguist-generated`.
 *
 * GitHub collapses `linguist-generated` files in pull-request diffs and leaves
 * them out of language statistics, and review-size checks and other tools that
 * honour the attribute count them as generated rather than hand-written. A
 * change that regenerates a package therefore reads as generated code, while
 * the generator change that caused it, in `@macts/core`, reads as hand-written.
 *
 * The marking rule, derived from the files one run emits, so a newly generated
 * package, or a new kind of emitted file, is marked without anyone maintaining
 * a list of package paths:
 *
 * - **`src/**`** is marked whenever the package emits a source file. A
 *   generated package's `src/` tree is wholly the generator's: every file under
 *   it is in the package's owned-output record.
 * - **Every other emitted file** is marked by its exact path, anchored at the
 *   package root with a leading `/` so a file of the same name deeper in the
 *   package is not swept in. This includes this file itself and the
 *   owned-output record (`./owned-output.ts`), which the writer, not an
 *   emitter, produces.
 * - **`package.json` is never marked.** Changesets rewrites its version and
 *   internal dependency ranges on every release, and its dependencies, exports
 *   and published `files` are what a reviewer must see; collapsing it would
 *   hide exactly the changes worth reading.
 *
 * Files the generator never emits, such as a package's `CHANGELOG.md`, are
 * never marked.
 *
 * @packageDocumentation
 */

import { OWNED_OUTPUT_RECORD_FILE, ownedOutputPaths } from './owned-output.js'

/** The name of the attributes file at the root of each generated package. */
export const GIT_ATTRIBUTES_FILE = '.gitattributes'

/** The attribute each marking line sets. */
const GENERATED_ATTRIBUTE = 'linguist-generated=true'

/** The directory whose whole tree a generated package's generator owns. */
const SOURCE_DIRECTORY = 'src/'

/** Emitted files deliberately left unmarked; see the module comment. */
const UNMARKED_FILES = new Set(['package.json'])

/** The file's opening comment, explaining it to a reader of the package. */
const HEADER = [
  '# Generated by macts generate; do not edit.',
  '# Marks the files the generator owns in this package as generated, so a diff',
  '# that regenerates the package shows them as generated code. package.json is',
  '# not marked: its version and dependencies change on release and are reviewed.',
]

/**
 * Characters that make a path something other than a literal gitattributes
 * pattern: whitespace ends a pattern, `*`, `?` and `[` are glob syntax, and
 * `\` and `"` are escape and quoting syntax.
 */
const NON_LITERAL_PATTERN_CHARACTER = /[\s*?[\]\\"]/

/**
 * The `.gitattributes` of a generated package, from the files its generator
 * run emits.
 *
 * @param files - The other files the run emits into the package, with
 * package-relative paths
 * @returns The `.gitattributes` file, to emit alongside them
 * @throws When an emitted path leaves the package, or a path marked exactly
 * cannot be written as a literal gitattributes pattern.
 */
export function generateGitAttributes(files: readonly { readonly path: string }[]): {
  path: string
  content: string
} {
  const paths = ownedOutputPaths(files)
  // The files marked by exact path: every emitted file outside `src/`.
  const exactFiles = new Set([GIT_ATTRIBUTES_FILE, OWNED_OUTPUT_RECORD_FILE])
  let hasSources = false
  for (const path of paths) {
    if (path.startsWith(SOURCE_DIRECTORY)) {
      hasSources = true
      continue
    }
    if (UNMARKED_FILES.has(path)) continue
    if (NON_LITERAL_PATTERN_CHARACTER.test(path)) {
      throw new Error(
        `Cannot mark generated file "${path}" in ${GIT_ATTRIBUTES_FILE}: its path is not a literal pattern.`
      )
    }
    exactFiles.add(path)
  }

  const rules = [
    ...(hasSources ? [`${SOURCE_DIRECTORY}** ${GENERATED_ATTRIBUTE}`] : []),
    ...[...exactFiles].sort().map((path) => `/${path} ${GENERATED_ATTRIBUTE}`),
  ]
  return { path: GIT_ATTRIBUTES_FILE, content: `${[...HEADER, ...rules].join('\n')}\n` }
}
